    fun imageUrl(emoteId: String): String {
        val clean = emoteId.trim()
        if (clean.isEmpty()) return ""
        val encoded = URLEncoder.encode(clean, "UTF-8").replace("+", "%20")
        val meta = BY_ID[clean]
        val suffix = if (meta?.animated == true) "?v=anim2" else ""
        return "$BASE_URL$encoded.webp$suffix"
    }
